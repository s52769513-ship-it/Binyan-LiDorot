// סכומים נשמרים ומוצגים באגורות (2 ספרות אחרי הנקודה). עיגול לשקל שלם מעלים
// או מוריד אגורות ומייצר פערים בין חוב, תשלום ויתרה — ולכן לא מעגלים לשלם.

/** עיגול לאגורה (2 ספרות) — הדיוק שבו סכומים נשמרים ומוצגים. */
export const round2 = (n: number): number => Math.round((Number(n) || 0) * 100) / 100
