-- שלב 2 של "מקור התנועה". כרגע המקור *נגזר* מסימנים קיימים (הערות, שיוך להו"ק,
-- synced_at) ולכן מוצג בממשק עם התווית "משוער". העמודה הזו מאפשרת לשמור את
-- המקור במפורש בעת היצירה, כך שתנועות חדשות יהיו ודאיות ולא משוערות.
--
-- חשוב: להריץ את הקובץ הזה *לפני* שמפעילים את שמירת המקור בקוד — אחרת כתיבה
-- לעמודה שאינה קיימת תיכשל, וזה נוגע לאוטומציות שמייבאות כסף.
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS source text;

-- אינדקס לסינון/דוחות לפי מקור (אופציונלי, זול).
CREATE INDEX IF NOT EXISTS idx_transactions_source ON transactions (source);
